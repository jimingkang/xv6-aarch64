#include <kernel/types.h>
#include <kernel/param.h>
#include "memlayout.h"
#include "aarch64.h"
#include <kernel/defs.h>
#include <kernel/device.h>
#include <kernel/kobject.h>
#include <kernel/module.h>

volatile static int started = 0;
extern char end[];  // first address after kernel loaded from ELF file

void _entry(void);
extern const char kernel_build_time[];   // generated by the Makefile at link
extern const char kernel_build_rev[];
void delay(uint32 c);
void boot_uart_mark(int c);

static void
start_secondary_cpus(void)
{
  // The standard Raspberry Pi AArch64 armstub parks CPU1..3 on spin-table
  // slots 0xe0, 0xe8 and 0xf0.  A custom armstub may already have sent them
  // to _entry; publishing these slots is harmless in that case.
  volatile uint64 *spin = (volatile uint64*)P2V(0xe0);
  uint64 entry = V2P((uint64)_entry);
  for(int cpu = 1; cpu < NCPU; cpu++){
    spin[cpu - 1] = entry;
    asm volatile("dc cvac, %0" :: "r"(&spin[cpu - 1]) : "memory");
  }
  asm volatile("dsb sy\n\tsev" ::: "memory");
}

// start() jumps here in EL1 on all CPUs.
void
main()
{
  boot_uart_mark('0');
  if(cpuid() == 0){
    // QEMU's Pi firmware parks secondary cores. This first port runs core 0.
    // kinit2() hands out RAM from EARLYTOP upward: the kernel image and its
    // BSS must end below it, or the allocator would reuse kernel memory.
    // printf is not ready yet, so report through the early boot UART.
    if(V2P(end) > EARLYTOP){
      for(char *m = "\nkernel image extends past EARLYTOP\n"; *m; m++)
        boot_uart_mark(*m);
      for(;;)
        asm volatile("wfe");
    }
    kinit1(end, P2V(EARLYTOP));  // memory covered by the bootstrap map
    //boot_uart_mark('1');
    kvminit();       // create kernel page table
    //boot_uart_mark('2');
    kvminithart();   // turn on paging
    //boot_uart_mark('3');
    kinit2(P2V(EARLYTOP), P2V(PHYSTOP));
    //boot_uart_mark('4');
    // The device model and the two bus cores are not modules: consoleinit()
    // below already calls register_chrdev() and platform_device_register(),
    // so they must exist before do_initcalls() runs the driver table.
    // The object model must exist before the driver core, which registers
    // kobjects into the sysfs tree it builds.  Neither is a module.
    kobject_subsys_init();
    device_init();
    sdio_bus_init();
    usb_bus_init();
    consoleinit();
    ttyinit();
    printfinit();
    printf("\n");
    printf("xv6 kernel is booting\n");
    printf("build: bcm43430-sdio-v2\n");
    printf("kernel image built: %s (%s)\n", kernel_build_time, kernel_build_rev);
    printf("\n");
    procinit();      // process table
    workqueue_init(); // schedulable bottom halves run on kworker
    rnginit();       // BCM2837 hardware random source for cryptographic keys
    syncinit();      // process synchronization objects
    netinit();       // Ethernet/IPv4/UDP stack (loopback until NIC attaches)
    trapinit();      // trap vectors
    trapinithart();  // install trap vector
    gicv3init();     // set up interrupt controller
    gicv3inithart();
    timerinit();
    binit();         // buffer cache
    iinit();         // inode table
    fileinit();      // file table
    // Drivers are no longer hand-listed here.  Each one put a struct
    // module_desc in the .initcall.list section with module_init() or a level
    // macro, and this walks the linker's table in (level, order) sequence:
    // input core, filesystems, host controllers and class drivers, then the
    // root mount and the modules that need firmware files from it.
    do_initcalls();
    userinit();      // first user process
#if VM_TRACE
    kvmdump();       // complete TTBR1 L1/L2/L3 walk, once before SMP starts
#endif
    start_secondary_cpus();
    __sync_synchronize();
    started = 1;
  } else {
    while(started == 0)
      ;
    __sync_synchronize();
    kvminithart();    // turn on paging
    printf("hart %d starting\n", cpuid());
    trapinithart();   // install trap vector
    gicv3inithart();
    timerinit();
  }

  scheduler();
}
